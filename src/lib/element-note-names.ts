/** Try every plain name before using a human-readable copy number. */
export function* elementNoteNames(used: Iterable<string>, random = Math.random): Generator<string> {
  const reserved = new Set(Array.from(used, name => name.toLowerCase()));
  const elements: string[] = [...ELEMENT_NAMES];
  for (let i = elements.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [elements[i], elements[j]] = [elements[j], elements[i]];
  }
  for (let copy = 1; ; copy++) {
    for (const element of elements) {
      const name = `${element}${copy === 1 ? "" : ` ${copy}`}.md`;
      if (!reserved.has(name.toLowerCase())) yield name;
    }
  }
}
